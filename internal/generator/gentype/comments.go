package gentype

import (
	"go/ast"
	"go/token"
	"regexp"
	"strings"

	"golang.org/x/tools/go/packages"
)

func GetDocComment(symbol string, structName string, doc string) string {
	rxGodoc := regexp.MustCompile(`^` + structName + ` godoc\s`)

	doc = strings.TrimSpace(doc)
	doc = rxGodoc.ReplaceAllString(doc, "")
	doc = strings.TrimSpace(doc)

	symbol += " "

	comment := strings.Builder{}

	if doc != "" {
		comment.WriteString(symbol)
		comment.WriteString(strings.ReplaceAll(doc, "\n", "\n"+symbol) + "\n\n")
	}

	comment.WriteString(symbol)
	comment.WriteString("This file is generated by github.com/kukymbr/configen; DO NOT EDIT.\n")
	comment.WriteString(symbol)
	comment.WriteString("Source struct: " + structName + "\n\n")

	return comment.String()
}

// PrefixCommentLines prefixes every line of the comment with the prefix (e.g. "# " or "// "),
// empty lines get the prefix without trailing spaces. Returns an empty string for an empty comment.
func PrefixCommentLines(comment string, prefix string) string {
	comment = strings.TrimSpace(comment)
	if comment == "" {
		return ""
	}

	lines := strings.Split(comment, "\n")

	for i, line := range lines {
		line = strings.TrimRight(line, " \t\r")

		if line == "" {
			lines[i] = strings.TrimRight(prefix, " ")

			continue
		}

		lines[i] = prefix + line
	}

	return strings.Join(lines, "\n")
}

func GetStructDocComment(pkg *packages.Package, structName string) string {
	for _, f := range pkg.Syntax {
		for _, decl := range f.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}

			for _, spec := range gen.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok || ts.Name.Name != structName {
					continue
				}

				if gen.Doc != nil {
					return strings.TrimSpace(gen.Doc.Text())
				}
			}
		}
	}

	return ""
}

func BuildCommentsMap(pkg *packages.Package) map[token.Pos]string {
	out := map[token.Pos]string{}

	for _, f := range pkg.Syntax {
		for _, decl := range f.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}

			for _, spec := range gen.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}

				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}

				for _, field := range st.Fields.List {
					if field.Doc != nil {
						out[field.Pos()] = strings.TrimSpace(field.Doc.Text())
					} else if field.Comment != nil {
						out[field.Pos()] = strings.TrimSpace(field.Comment.Text())
					}
				}
			}
		}
	}

	return out
}
